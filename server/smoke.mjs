import WebSocket from 'ws';
const mk = () => new Promise(r => { const w = new WebSocket('ws://localhost:3001/ws'); w.on('open', () => r(w)); });
const log = (who) => (d) => { const m = JSON.parse(d); console.log(who, m.type, m.payload.message ?? m.payload.room?.players?.map(p => p.name + (p.isHost ? '*' : '')) ?? ''); };
const a = await mk(); a.on('message', log('A'));
const b = await mk(); b.on('message', log('B'));
const send = (w, type, payload) => w.send(JSON.stringify({ type, payload }));
let code;
a.on('message', d => { const m = JSON.parse(d); if (m.type === 'room_joined') code = m.payload.room.code; });
send(a, 'create_room', { hostName: 'Asha', settings: { rounds: 99, drawTime: 5 } });
await new Promise(r => setTimeout(r, 200));
send(b, 'join_room', { roomCode: code.toLowerCase(), playerName: 'Ben' });
await new Promise(r => setTimeout(r, 200));
send(a, 'start_game', {});
send(b, 'set_ready', { ready: true });
await new Promise(r => setTimeout(r, 100));
send(a, 'start_game', {});
send(b, 'nonsense', {});
await new Promise(r => setTimeout(r, 200));
process.exit(0);
